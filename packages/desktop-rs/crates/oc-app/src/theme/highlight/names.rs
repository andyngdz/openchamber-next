//! The syntax keys and token names this highlighter port speaks, each string once.
//!
//! `RULES` names and every key `resolveSyntaxTokens` looks up share this table, so a
//! misspelled name is one edit and no literal is repeated across the crate.

macro_rules! names {
    ($($variant:ident => $literal:literal),* $(,)?) => {
        /// A syntax base key, a resolved token key, or a `TOKEN_RULES` token name.
        #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
        pub(super) enum Token {
            $($variant),*
        }

        impl Token {
            pub(super) const fn as_str(self) -> &'static str {
                match self {
                    $(Self::$variant => $literal),*
                }
            }
        }
    };
}

